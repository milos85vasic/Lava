// cmdGen writes the four tracker docs to the out dir.
func cmdGen(args []string) error {
	f, err := parseFlags(args)
	if err != nil {
		return err
	}
	path := dbPath(f)
	if err := mustExist(path); err != nil {
		return err
	}
	dir := outDir(f)
	if err := ensureDir(dir); err != nil {
		return err
	}
	db, err := openDB(path)
	if err != nil {
		return err
	}
	defer db.Close()
	all, err := loadAll(db)
	if err != nil {
		return err
	}
	docs := renderDocs(all)
	for name, body := range docs {
		if err := os.WriteFile(filepath.Join(dir, name), body, 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", name, err)
		}
		fmt.Printf("wrote %s (%d bytes)\n", filepath.Join(dir, name), len(body))
	}
	return nil
}

// cmdVerify regenerates the docs in-memory and byte-compares against the on-disk
// files (§11.4.106 byte-identical round-trip). Exit non-zero on any mismatch.
func cmdVerify(args []string) error {
	f, err := parseFlags(args)
	if err != nil {
		return err
	}
	path := dbPath(f)
	if err := mustExist(path); err != nil {
		return err
	}
	dir := outDir(f)
	db, err := openDB(path)
	if err != nil {
		return err
	}
	defer db.Close()
	all, err := loadAll(db)
	if err != nil {
		return err
	}
	docs := renderDocs(all)
	names := []string{docIssues, docFixed, docIssuesSummary, docFixedSummary}
	mismatch := false
	for _, name := range names {
		want := docs[name]
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			fmt.Printf("VERIFY FAIL %s: %v\n", name, err)
			mismatch = true
			continue
		}
		if !bytes.Equal(want, got) {
			fmt.Printf("VERIFY FAIL %s: on-disk md differs from regenerated DB output (%d on-disk vs %d generated bytes)\n",
				name, len(got), len(want))
			mismatch = true
			continue
		}
		fmt.Printf("VERIFY PASS %s (byte-identical, %d bytes)\n", name, len(want))
	}
	if mismatch {
		return fmt.Errorf("§11.4.106 round-trip FAILED — run `lava-tickets gen` to resync")
	}
	fmt.Println("VERIFY: all four trackers byte-identical with the DB (§11.4.106 PASS)")
	return nil
}

// cmdImport reconstructs ticket rows from the markdown trackers and replays them
// into a (typically empty) DB. It parses Issues.md + Fixed.md tables and verifies
// the reconstructed core fields (id/type/status/title) match. This proves the md
// is a faithful projection of the DB (the inverse direction of §11.4.106).
func cmdImport(args []string) error {
	f, err := parseFlags(args)
	if err != nil {
		return err
	}
	path := dbPath(f)
	if err := mustExist(path); err != nil {
		return err
	}
	dir := f["in"]
	if dir == "" {
		dir = defaultOut
	}
	parsed, err := parseTrackers(dir)
	if err != nil {
		return err
	}
	db, err := openDB(path)
	if err != nil {
		return err
	}
	defer db.Close()
	// Compare the parsed projection against the DB's own projection.
	all, err := loadAll(db)
	if err != nil {
		return err
	}
	dbProj := map[string]projRow{}
	for _, t := range all {
		dbProj[t.id] = projRow{id: t.id, typ: t.typ, status: renderedStatus(t), title: mdEscape(t.title)}
	}
	mismatch := 0
	for id, p := range parsed {
		d, ok := dbProj[id]
		if !ok {
			fmt.Printf("IMPORT MISMATCH %s: present in md, absent in DB\n", id)
			mismatch++
			continue
		}
		if p.typ != d.typ || p.status != d.status || p.title != d.title {
			fmt.Printf("IMPORT MISMATCH %s: md{type=%q,status=%q,title=%q} != db{type=%q,status=%q,title=%q}\n",
				id, p.typ, p.status, p.title, d.typ, d.status, d.title)
			mismatch++
			continue
		}
	}
	for id := range dbProj {
		if _, ok := parsed[id]; !ok {
			fmt.Printf("IMPORT MISMATCH %s: present in DB, absent in md\n", id)
			mismatch++
		}
	}
	if mismatch > 0 {
		return fmt.Errorf("import reconciliation FAILED: %d mismatch(es)", mismatch)
	}
	fmt.Printf("IMPORT PASS: %d tickets in md reconcile exactly with DB rows\n", len(parsed))
	return nil
}

type projRow struct{ id, typ, status, title string }

// parseTrackers reads Issues.md + Fixed.md and extracts the core projection
// (id, type, status, title) from each table row.
func parseTrackers(dir string) (map[string]projRow, error) {
	out := map[string]projRow{}
	// Issues.md: cols = LVA ID | Type | Status | Priority | Title | Source | Source Ref
	if err := parseTable(filepath.Join(dir, docIssues), func(cells []string) {
		if len(cells) >= 5 && strings.HasPrefix(cells[0], "LVA-") {
			out[cells[0]] = projRow{id: cells[0], typ: cells[1], status: cells[2], title: cells[4]}
		}
	}); err != nil {
		return nil, err
	}
	// Fixed.md: cols = LVA ID | Type | Status | Title | Fix SHA | ...
	if err := parseTable(filepath.Join(dir, docFixed), func(cells []string) {
		if len(cells) >= 4 && strings.HasPrefix(cells[0], "LVA-") {
			out[cells[0]] = projRow{id: cells[0], typ: cells[1], status: cells[2], title: cells[3]}
		}
	}); err != nil {
		return nil, err
	}
	return out, nil
}

// parseTable streams a markdown file and invokes fn for each pipe-table data row
// (skipping the header + separator). Header detection is by the presence of the
// separator row "|----|...".
func parseTable(path string, fn func(cells []string)) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 1024*1024), 1024*1024)
	inTable := false
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if !strings.HasPrefix(line, "|") {
			inTable = false
			continue
		}
		// separator row → table body starts after it
		if strings.Contains(line, "---") {
			inTable = true
			continue
		}
		if !inTable {
			continue // this is the header row (before separator)
		}
		cells := splitRow(line)
		fn(cells)
	}
	return sc.Err()
}

func splitRow(line string) []string {
	line = strings.Trim(line, "|")
	parts := strings.Split(line, "|")
	out := make([]string, len(parts))
	for i, p := range parts {
		// reverse the mdEscape pipe-escaping
		out[i] = strings.TrimSpace(strings.ReplaceAll(p, "\\|", "|"))
	}
	return out
}
